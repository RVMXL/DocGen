// ── Заголовки каталога и стран на разных языках интерфейса ─────────────────

/** Заголовок шаблона: ru-интерфейс → titleRu, en → titleEn, иначе → titleDoc (язык документа) */
export function tplTitle(
  t: { titleRu: string; titleEn: string; titleDoc?: string | null },
  lang: Locale
): string {
  if (lang === 'ru') return t.titleRu;
  if (lang === 'en') return t.titleEn;
  return t.titleDoc ?? t.titleEn;
}

/** Описание шаблона (правило то же) */
export function tplDesc(
  t: { descRu: string; descEn: string; descDoc?: string | null },
  lang: Locale
): string {
  if (lang === 'ru') return t.descRu;
  if (lang === 'en') return t.descEn;
  return t.descDoc ?? t.descEn;
}

/** Заголовок группы/подгруппы каталога */
export function catTitle(
  t: { titleRu: string; titleEn: string; titleI18n?: Partial<Record<string, string>> },
  lang: Locale
): string {
  if (lang === 'ru') return t.titleRu;
  if (lang === 'en') return t.titleEn;
  return t.titleI18n?.[lang] ?? t.titleEn;
}

/** Название страны */
export function countryName(
  c: { nameRu: string; nameEn: string; nameI18n?: Partial<Record<string, string>> },
  lang: Locale
): string {
  if (lang === 'ru') return c.nameRu;
  if (lang === 'en') return c.nameEn;
  return c.nameI18n?.[lang] ?? c.nameEn;
}

/** Локали, носители которых обычно читают русские подписи (правовое поле постсоветского пространства) */
const RU_FAMILIAR: ReadonlySet<string> = new Set(['uk', 'be', 'kk', 'uz', 'kg', 'tg', 'hy', 'az', 'ro']);

/** Подпись поля формы: ru-семейство интерфейсов → русский, остальные → английский */
export function fieldLabel(
  f: { labelRu: string; labelEn: string },
  lang: Locale
): string {
  if (lang === 'ru') return f.labelRu;
  if (lang === 'en') return f.labelEn;
  return RU_FAMILIAR.has(lang) ? (f.labelRu || f.labelEn) : (f.labelEn || f.labelRu);
}

/** Подсказка поля (тот же принцип) */
export function fieldHint(
  f: { hintRu?: string | null; hintEn?: string | null },
  lang: Locale
): string {
  if (lang === 'ru') return f.hintRu ?? '';
  if (lang === 'en') return f.hintEn ?? '';
  return (RU_FAMILIAR.has(lang) ? (f.hintRu ?? f.hintEn ?? '') : (f.hintEn ?? f.hintRu ?? ''));
}
